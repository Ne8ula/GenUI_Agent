// Actual Windows input through the existing guarded, synthetic-only probe.
import assert from "node:assert/strict";
import { execFileSync, spawn } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
const [fixturePid,stateFile,nativePid,output]=process.argv.slice(2);
if(!output) throw Error("fixturePid stateFile nativePid freshOutputDirectory required");
const out=resolve(output);mkdirSync(out);
const {chromium}=await import(process.env.E1_PLAYWRIGHT_MODULE?pathToFileURL(resolve(process.env.E1_PLAYWRIGHT_MODULE)).href:"playwright");
const browser=await chromium.connectOverCDP("http://127.0.0.1:9223");
const pages=browser.contexts().flatMap(c=>c.pages());
const main=pages.find(p=>p.url()==="http://127.0.0.1:1431/");
const material=pages.find(p=>new URL(p.url()).searchParams.get("layer")==="material");
if(!main||!material)throw Error("Both native layers required");
const result={kind:"native Windows, real OS clicks; microphone and provider calls not run",checks:[],errors:[]};
for(const p of [main,material])p.on("pageerror",e=>result.errors.push(e.message));
const common=["-FixtureProcessId",fixturePid,"-StatePath",stateFile,"-E1ProcessId",nativePid];
const probe=args=>JSON.parse(execFileSync("powershell.exe",["-NoProfile","-File",resolve("experiments/e1/scripts/desktop-probe.ps1"),...common,...args],{encoding:"utf8",windowsHide:true}));
const fixture=()=>JSON.parse(readFileSync(stateFile,"utf8"));
const state=()=>main.evaluate(()=>window.__E1_WEAVE_TEST__.getSnapshot());
const check=(label,value)=>{assert.ok(value,label);result.checks.push(label);};
const click=async locator=>{await locator.scrollIntoViewIfNeeded();const r=await locator.boundingBox();assert.ok(r);probe(["-Action","Click","-X",String(Math.round(r.x+r.width/2)),"-Y",String(Math.round(r.y+r.height/2))]);};
const capture=(name,mode="light")=>probe(["-Action","Capture","-FixtureMode",mode,"-ScreenshotPath",resolve(out,name+".png")]);
const settle=()=>main.waitForFunction(()=>window.__E1_WEAVE_TEST__.getSnapshot().transition.status!=="active");
const button=name=>main.getByRole("button",{name,exact:true});
let recorderExit;
try{
  await main.reload();await main.waitForFunction(()=>window.__E1_WEAVE_TEST__?.voice());
  await material.waitForSelector(".weave-material");
  result.geometry=await main.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio,left:screenX,top:screenY,userAgent:navigator.userAgent,native:!!window.__TAURI_INTERNALS__}));
  check("native two-layer host",result.geometry.native&&await material.evaluate(()=>!!window.__TAURI_INTERNALS__));
  check("controlled physical coordinate mapping",result.geometry.dpr===1&&result.geometry.width===fixture().client.width&&result.geometry.height===fixture().client.height);
  check("native does not draw mock desktop",await main.locator(".weave-backdrop").count()===0);
  probe(["-Action","Capture","-PrepareFixture"]);
  await click(button("Controls +"));await click(button("Mute answer"));
  check("narration explicitly muted before all provider-capable requests",await main.evaluate(()=>!window.__E1_WEAVE_TEST__.voice().getState().audioEnabled));
  await click(button("Controls −"));
  await material.waitForTimeout(1200);capture("native-idle");
  const before=fixture().clickCount;
  probe(["-Action","Click","-X","1280","-Y","668"]);
  check("original eye passes actual OS input",fixture().clickCount===before+1);
  const recorder=spawn("powershell.exe",["-NoProfile","-File",resolve("experiments/e1/scripts/record-native.ps1"),...common,"-OutputDirectory",resolve(out,"recording"),"-DurationSeconds","35","-FramesPerSecond","10"],{stdio:["ignore","pipe","pipe"],windowsHide:true});
  let recorderError="";recorder.stderr.on("data",d=>recorderError+=d.toString());
  recorderExit=new Promise(resolveExit=>recorder.once("exit",code=>resolveExit({code,error:recorderError})));
  await new Promise((ready,reject)=>{let text="";const timer=setTimeout(()=>reject(Error("Recorder readiness timeout")),15000);recorder.stdout.on("data",d=>{text+=d.toString();if(text.includes('"recording-start"')){clearTimeout(timer);ready();}});recorder.once("exit",()=>{clearTimeout(timer);reject(Error(recorderError));});});
  await click(button("Controls +"));const requestBefore=fixture().clickCount;
  await click(button("Today in NYC"));await click(button("Controls −"));await settle();
  check("OS weather request reaches overlay",fixture().clickCount===requestBefore&&(await state()).forecast.temperatureC===22);
  capture("native-sunny");
  const materialBefore=fixture().clickCount;probe(["-Action","Click","-X","1280","-Y","500"]);
  check("weather material passes actual OS input",fixture().clickCount===materialBefore+1);
  const move=button("Move weather composition. Use arrow keys to move");const r=await move.boundingBox();
  probe(["-Action","Drag","-StartX",String(Math.round(r.x+60)),"-StartY",String(Math.round(r.y+35)),"-EndX",String(Math.round(r.x+110)),"-EndY",String(Math.round(r.y+70))]);
  await click(button("Pin"));const pin=(await state()).anchors["12:00"];
  check("actual OS drag and pin update geometry",pin.pinned&&pin.userMoved);
  await click(button("Controls +"));await click(button("Tomorrow"));await click(button("Controls −"));await settle();
  assert.deepEqual((await state()).anchors["12:00"],pin);check("tomorrow retains NYC and pin",(await state()).forecast.date==="2026-10-15"&&(await state()).forecast.temperatureC===16);
  capture("native-rainy-light");capture("native-rainy-dark","dark");capture("native-rainy-busy","busy-neutral");
  await click(button("Stop"));await material.waitForTimeout(150);const draws=await material.locator("canvas").getAttribute("data-draw-count");await material.waitForTimeout(200);
  check("native Stop arrests material",draws===await material.locator("canvas").getAttribute("data-draw-count"));
  await click(button("Controls +"));await click(button("Plain answer"));capture("native-plain");await click(button("Dismiss weather"));await click(button("Controls −"));await material.waitForTimeout(1000);
  check("weather dismissal keeps native idle eye",(await state()).status==="dismissed"&&await material.locator("canvas").getAttribute("data-form")==="eye");
  capture("native-returned-eye");
  const after=fixture().clickCount;probe(["-Action","Click","-X",String(Math.round(r.x+60)),"-Y",String(Math.round(r.y+35))]);
  check("dismissed forecast region passes actual OS input",fixture().clickCount===after+1);
  check("microphone never enabled in this exercise",await main.evaluate(()=>!window.__E1_WEAVE_TEST__.voice().getState().enabled));
  check("no native errors",result.errors.length===0);
  const recording=await recorderExit;check("guarded native interaction recording completed",recording.code===0);result.completed=true;
}catch(error){result.failure=String(error);process.exitCode=1;if(recorderExit)result.recording=await recorderExit;}
finally{writeFileSync(resolve(out,"checks.json"),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));await browser.close();}
