import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const args = new Set(process.argv.slice(2));
const supportedArgs = new Set(["--check"]);
for (const arg of args) {
  if (!supportedArgs.has(arg)) throw new Error(`Unknown argument: ${arg}`);
}

const generatedDirectory = new URL("../src/core/generated/", import.meta.url);
const validatorModule = new URL("validators.js", generatedDirectory);
const validatorDeclaration = new URL("validators.d.ts", generatedDirectory);
const schemaDefinitions = [
  {
    exportName: "validateWeatherFixture",
    path: "schemas/weather-fixture.schema.json",
    url: new URL("../schemas/weather-fixture.schema.json", import.meta.url),
  },
  {
    exportName: "validateModelProposal",
    path: "schemas/model-proposal.schema.json",
    url: new URL("../schemas/model-proposal.schema.json", import.meta.url),
  },
];

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function convertRuntimeHelpersToEsm(source) {
  const runtimeImports = new Map();
  const converted = source.replace(
    /const (func\d+) = require\("(ajv\/dist\/runtime\/[^".]+)"\)\.default;\s*/g,
    (_match, binding, specifier) => {
      let importName = runtimeImports.get(specifier);
      if (!importName) {
        importName = `ajvRuntime${runtimeImports.size}`;
        runtimeImports.set(specifier, importName);
      }
      return `const ${binding} = typeof ${importName} === "function" ? ${importName} : ${importName}.default;\n`;
    },
  );

  if (/\brequire\s*\(/.test(converted)) {
    throw new Error("Generated validator contains an unsupported CommonJS runtime helper");
  }

  const imports = [...runtimeImports].map(
    ([specifier, importName]) => `import ${importName} from "${specifier}.js";`,
  );
  return `${imports.join("\n")}\n${converted}`;
}

async function renderValidators() {
  const schemas = await Promise.all(
    schemaDefinitions.map(async (definition) => {
      const raw = await readFile(definition.url, "utf8");
      const schema = JSON.parse(raw);
      if (typeof schema.$id !== "string" || schema.$id.length === 0) {
        throw new Error(`${definition.path} must declare a non-empty $id`);
      }
      return { ...definition, schema };
    }),
  );

  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true, lines: true },
  });
  for (const { schema } of schemas) ajv.addSchema(schema);

  const exportsByName = Object.fromEntries(
    schemas.map(({ exportName, schema }) => [exportName, schema.$id]),
  );
  const standalone = standaloneCode(ajv, exportsByName);
  const sourceManifest = schemas
    .map(({ path, schema }) => ` * - ${path} (schema-json sha256 ${sha256(JSON.stringify(schema))})`)
    .join("\n");
  const header = `/**\n * Generated by scripts/generate-validators.mjs. Do not edit.\n${sourceManifest}\n */\n`;

  return `${header}${convertRuntimeHelpersToEsm(standalone).trimStart()}\n`;
}

const declaration = `/** Generated by scripts/generate-validators.mjs. Do not edit. */
import type { ErrorObject } from "ajv";
import type { ModelProposal, WeatherFixture } from "../types.js";

export interface StandaloneValidator<T> {
  (data: unknown): data is T;
  errors: ErrorObject[] | null;
}

export const validateWeatherFixture: StandaloneValidator<WeatherFixture>;
export const validateModelProposal: StandaloneValidator<ModelProposal>;
`;

async function checkCurrent(url, expected) {
  try {
    return (await readFile(url, "utf8")) === expected;
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}

const validatorSource = await renderValidators();
if (args.has("--check")) {
  const [moduleCurrent, declarationCurrent] = await Promise.all([
    checkCurrent(validatorModule, validatorSource),
    checkCurrent(validatorDeclaration, declaration),
  ]);
  if (!moduleCurrent || !declarationCurrent) {
    console.error("Standalone validators are stale. Run npm run generate:validators.");
    process.exitCode = 1;
  }
} else {
  await mkdir(generatedDirectory, { recursive: true });
  await Promise.all([
    writeFile(validatorModule, validatorSource, "utf8"),
    writeFile(validatorDeclaration, declaration, "utf8"),
  ]);
}
