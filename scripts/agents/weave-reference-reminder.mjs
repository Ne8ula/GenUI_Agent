// Reinforce the shared design process without uploading data or spending credits.
const chunks = [];
for await (const chunk of process.stdin) chunks.push(chunk);
const input = JSON.parse(Buffer.concat(chunks).toString('utf8'));
const event = input.hook_event_name;

if (['SessionStart', 'SubagentStart', 'PreToolUse'].includes(event)) {
  const additionalContext = [
    'EVA mandatory Weave reference gate: read AGENTS.md and docs/design/FIGMA_WEAVE.md.',
    'Before every frontend/UI change, redesign, reimplementation or new visual pass,',
    'generate fresh task-scoped image references through direct Weave model calls OR a reusable Weave workflow;',
    'no manually authored graph is required for each task.',
    'Also generate video references for motion, transitions or temporal interaction changes.',
    'Inspect actual outputs; record route, model ID or workflow/version, real run IDs, settings and cost approval.',
    'Store each pass under its revision: REVIEW.md, references/contact-sheet.png, references/images/,',
    'references/videos/, implementation/before/, implementation/after/, and provenance.json.',
    'Mark selected references in REVIEW.md, link it from the phase index and give the packet to every UI writer.',
    'No UI edits before this prerequisite. One packet covers its bounded pass, not unrelated later work.',
    'If access, a usable Weave model/workflow, cost approval or inspectable outputs are missing, stop UI work',
    'and request the missing prerequisite. Never substitute procedural-only design or another provider.',
    'Cloud may use a current task-specific packet generated by the connected main session;',
    'it must inspect that packet before edits and stop for a new packet on the next visual pass.',
    'Unrelated non-UI work may continue. Preserve normal cost confirmations and all phase gates.',
    'This hook is a process reminder, not proof of generation, visual inspection or owner acceptance.',
  ].join(' ');
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: { hookEventName: event, additionalContext },
  }));
}
