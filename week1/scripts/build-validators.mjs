import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
for (const name of ["weather", "document", "patch"]) {
  ajv.addSchema(JSON.parse(readFileSync(new URL("../packages/protocol/" + name + ".schema.json", import.meta.url))), name);
}
const output = new URL("../packages/protocol/generated/", import.meta.url);
mkdirSync(output, { recursive: true });
writeFileSync(new URL("validators.mjs", output), "// Generated by npm run protocol:generate. No runtime code generation.\n" +
  standaloneCode(ajv, { validateWeather: "weather", validateDocument: "document", validatePatch: "patch" }));
writeFileSync(new URL("validators.d.mts", output), ["validateWeather", "validateDocument", "validatePatch"].map(name =>
  "export declare function " + name + "(value: unknown): boolean;").join("\n") + "\n");

