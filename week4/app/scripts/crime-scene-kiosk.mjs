// Cloud demo only: GPU Chromium on the virtual display, streamed through noVNC.
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {browserOptions} from './browser-options.mjs';
assert.equal(process.env.EVA_REQUIRE_NVIDIA, '1', 'Modal GPU only');
const output = process.argv[2];
await mkdir(output, {recursive: true});
const options = browserOptions();
const browser = await chromium.launch({...options, headless: false, args: [...(options.args ?? []), '--kiosk', '--window-position=0,0', '--window-size=1600,900']});
const page = await browser.newPage({viewport: {width: 1600, height: 900}, hasTouch: true});
// A new Playwright window did not inherit --kiosk; use the actual window bounds.
const display = await page.context().newCDPSession(page);
const {windowId} = await display.send('Browser.getWindowForTarget');
await display.send('Browser.setWindowBounds', {windowId, bounds: {windowState: 'fullscreen'}});
await display.detach();
page.setDefaultTimeout(15000);
const report = {status: 'failed', checks: [], errors: [], gpu: null};
page.on('pageerror', error => report.errors.push(error.message));
page.on('console', message => { if (/THREE.WebGLProgram|shader error|VALIDATE_STATUS|GL_INVALID_OPERATION/i.test(message.text())) report.errors.push(message.text()); });
await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
const capture = name => page.screenshot({path: join(output, name + '.png')});
try {
  await page.goto('http://127.0.0.1:1440/?scene=crime-scene');
  await page.locator('.panorama-app[data-phase="ready"]').waitFor({timeout: 60000});
  const canvas = page.locator('.panorama-stage canvas');
  report.gpu = await canvas.evaluate(canvas => {
    const gl = canvas.getContext('webgl2'), info = gl?.getExtension('WEBGL_debug_renderer_info');
    return {renderer: info ? gl.getParameter(info.UNMASKED_RENDERER_WEBGL) : '', buffer: [gl.drawingBufferWidth, gl.drawingBufferHeight]};
  });
  assert.match(report.gpu.renderer, /NVIDIA/i);
  assert.doesNotMatch(report.gpu.renderer, /swiftshader|llvmpipe|software/i);
  const clip = {x: 500, y: 280, width: 500, height: 300};
  const initial = await page.screenshot({clip});
  await capture('opening-normal');
  await page.getByRole('button', {name: 'Detective Mode', exact: true}).click();
  await page.locator('.panorama-app[data-mode="detective"]').waitFor();
  await capture('opening-matrix');
  await page.getByRole('button', {name: 'Exit Detective Mode', exact: true}).click();
  assert.deepEqual(await page.screenshot({clip}), initial, 'Opening pair must retain the default camera and restore normal appearance');
  report.checks.push('matched default-view normal and Matrix captures; exact normal restoration');
  await canvas.focus();
  for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight');
  const turned = await page.screenshot({clip});
  assert.notDeepEqual(turned, initial, 'Keyboard camera control must change the room view');
  await capture('room-normal');
  await page.getByRole('button', {name: 'Play demo'}).click();
  await page.getByRole('button', {name: 'Pause', exact: true}).click();
  assert.deepEqual(await page.screenshot({clip}), turned, 'Replay must retain the explored viewpoint');
  const frozen = await page.locator('.panorama-app').getAttribute('data-seconds');
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.panorama-app').getAttribute('data-seconds'), frozen);
  await page.getByRole('button', {name: 'Resume', exact: true}).click();
  await page.waitForFunction(value => Number(document.querySelector('.panorama-app')?.dataset.seconds) > Number(value), frozen);
  await page.getByRole('button', {name: 'Pause', exact: true}).click();
  report.checks.push('resume advances the paused replay');
  await page.getByRole('button', {name: 'Detective Mode', exact: true}).click();
  await page.locator('.panorama-app[data-mode="detective"]').waitFor();
  await capture('room-matrix');
  assert.notDeepEqual(await page.screenshot({clip}), turned, 'Matrix treatment must change room pixels');
  await page.getByRole('button', {name: 'Source photograph', exact: true}).focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => { const img = document.querySelector('.inspection-evidence img'); return img?.complete && img.naturalWidth > 0; });
  await capture('room-source');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', {name: 'Source photograph', exact: true}).evaluate(el => el === document.activeElement), true);
  await page.getByRole('button', {name: 'Exit Detective Mode', exact: true}).click();
  assert.deepEqual(await page.screenshot({clip}), turned, 'Normal appearance and camera must restore exactly');
  await capture('room-restored');
  report.checks.push('keyboard camera movement', 'replay retains explored viewpoint', 'pause holds time', 'radial sweep settles to Matrix', 'source photo decoded; Escape restores focus', 'normal mode restores exact central crop');
  await page.getByRole('button', {name: 'Reset', exact: true}).click();
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.setViewportSize({width: 390, height: 844});
  await capture('mobile-normal');
  await page.getByRole('button', {name: 'Detective Mode', exact: true}).tap();
  assert.equal(await page.locator('.panorama-app').getAttribute('data-mode'), 'detective');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await capture('mobile-matrix');
  await page.getByRole('button', {name: 'Source photograph', exact: true}).tap();
  await page.getByRole('button', {name: 'Close inspection'}).tap();
  report.checks.push('390px touch controls and source dismissal; no overflow', 'reduced-motion activation settles without sweep');
  await page.setViewportSize({width: 1600, height: 900});
  await page.emulateMedia({reducedMotion: 'no-preference'});
  const beforeDrag = await page.screenshot({clip});
  await page.mouse.move(750, 400); await page.mouse.down();
  await page.mouse.move(850, 420, {steps: 8}); await page.mouse.up();
  assert.notDeepEqual(await page.screenshot({clip}), beforeDrag, 'Pointer drag must change the camera');
  report.checks.push('pointer drag changes camera in Matrix mode');
  await page.getByRole('button', {name: 'Reset', exact: true}).click();
  await page.getByRole('button', {name: 'Play demo', exact: false}).click();
  await page.locator('.panorama-app[data-mode="scan"]').waitFor();
  await page.locator('.panorama-app[data-mode="detective"]').waitFor();
  await page.locator('.inspection-evidence').waitFor();
  await page.waitForFunction(() => document.querySelector('.panorama-app')?.dataset.seconds === '28.00', null, {timeout: 35000});
  assert.equal(await page.locator('.panorama-app').getAttribute('data-mode'), 'normal');
  assert.equal(await page.locator('.inspection-evidence').count(), 0);
  assert.deepEqual(await page.screenshot({clip}), initial, 'Complete replay returns to the original room and camera');
  report.checks.push('complete 28-second demo: scan, Matrix, source, normal return');
  // Leave the exact checked opening view ready for the owner to record.
  await page.getByRole('button', {name: 'Reset', exact: true}).click();
  await capture('room-live');
  await canvas.focus();
  assert.deepEqual(report.errors, []);
  report.status = 'passed';
} catch (error) {
  report.error = String(error);
  await capture('failure').catch(() => {});
} finally {
  await writeFile(join(output, 'result.json'), JSON.stringify(report, null, 2));
}
if (report.status !== 'passed') { await browser.close(); process.exitCode = 1; }
else browser.on('disconnected', () => process.exit(1));
