import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
import { browserOptions } from './browser-options.mjs';

const url = process.env.EVA_BEDROOM_URL ?? 'http://127.0.0.1:1440/?scene=teal-bedroom';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(url).hostname), 'Real scan verification stays on loopback.');
const destination = process.env.EVA_EVIDENCE_DIR ?? '.local/reconstruction/authored-ceiling-verification';
const browser = await chromium.launch(browserOptions());
try {
  await fs.mkdir(destination, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, reducedMotion: 'reduce', hasTouch: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.getByRole('button', { name: 'Ceiling light', exact: true }).waitFor();
  assert.equal(await page.locator('input[type=file]').count(), 0, 'demo requires no uploads');
  const snapshot = () => page.evaluate(() => window.__evaBedroom.snapshot());
  const initial = await snapshot();
  assert.equal(initial.mode, 'matrix'); assert.equal(initial.ceilingEnabled, true);
  assert.equal(initial.sourceTriangles, 1144903); assert.ok(initial.ceilingVertices > 1000);
  assert.ok(initial.completionVertices > 1000, 'room completion is loaded');
  await page.screenshot({ path: `${destination}/matrix.png` });
  const capture = () => page.evaluate(async () => {
    const value = await window.__evaBedroom.capture([0, 3, -.3], [-.2, 3.6, 1.05]);
    return { rgb: value.rgb, depth: value.depth };
  });
  const source = await capture();
  const toggle = page.getByRole('button', { name: 'Authored room', exact: true });
  await toggle.focus(); await page.keyboard.press('Enter');
  assert.equal((await snapshot()).ceilingEnabled, false);
  assert.deepEqual(await capture(), source);
  await page.screenshot({ path: `${destination}/original.png` });
  await page.keyboard.press('Space');
  assert.deepEqual((await snapshot()).camera, initial.camera);
  const geometries = (await snapshot()).geometries;
  for (let i = 0; i < 5; i++) { await toggle.click(); await toggle.click(); }
  assert.equal((await snapshot()).geometries, geometries);
  await page.getByRole('button', { name: 'Surfaces', exact: true }).click();
  await page.screenshot({ path: `${destination}/surface.png` });
  await page.getByRole('button', { name: 'Turn right', exact: true }).click();
  await page.screenshot({ path: `${destination}/oblique.png` });
  await page.getByRole('button', { name: 'Reset view', exact: true }).click();
  await page.getByRole('button', { name: 'Add teddy', exact: true }).click();
  await page.getByRole('button', { name: 'Make it blue', exact: true }).click();
  const memory = await snapshot();
  await page.getByRole('button', { name: 'Remove teddy', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal((await snapshot()).teddyVisible, true);
  assert.equal((await snapshot()).teddyColor, memory.teddyColor);
  await page.screenshot({ path: `${destination}/room-teddy.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Ceiling light', exact: true }).tap();
  await page.getByRole('button', { name: 'Matrix', exact: true }).tap();
  await toggle.tap(); await toggle.tap();
  const clipped = await page.locator('button:visible').evaluateAll(buttons => buttons.filter(button => { const r = button.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth || r.height < 44 || r.width < 44; }).map(button => button.textContent));
  assert.deepEqual(clipped, []);
  await page.screenshot({ path: `${destination}/mobile.png` });
  await toggle.tap();
  await page.evaluate(() => document.querySelector('canvas').dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
  await page.getByRole('button', { name: 'Reopen room', exact: true }).click();
  await page.getByRole('button', { name: 'Ceiling light', exact: true }).waitFor();
  assert.equal((await snapshot()).ceilingEnabled, false, 'hidden authored light stays hidden on recovery');
  assert.equal((await snapshot()).teddyColor, memory.teddyColor);
  assert.equal((await snapshot()).teddyVisible, true);
  assert.deepEqual(errors, []);
  const checks = { date: new Date().toISOString(), initial, recovered: await snapshot(), errors, passed: ['automatic verified scan load', 'no file inputs', 'authored light and Matrix default', 'immutable source capture', 'keyboard and touch toggle', 'camera continuity', 'stable toggle geometry count', 'teddy add/blue/remove/undo', 'mobile controls', 'simulated graphics recovery retains hidden light'] };
  await fs.writeFile(`${destination}/checks.json`, JSON.stringify(checks, null, 2) + '\n');
  console.log(JSON.stringify(checks, null, 2));
} finally { await browser.close(); }
