import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { browserOptions } from './browser-options.mjs';

const out = process.env.EVA_BEDROOM_EVIDENCE ?? fileURLToPath(new URL(`../../../docs/design/revisions/teal-bedroom-demo-v1/implementation/check-${Date.now()}`, import.meta.url));
const url = process.env.EVA_BEDROOM_URL ?? 'http://127.0.0.1:1440/?scene=teal-bedroom';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(url).hostname), 'Real scan verification stays on loopback.');
await mkdir(out);
const browser = await chromium.launch(browserOptions());
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(url);
  await page.getByRole('heading', { name: 'The teal bedroom', exact: true }).waitFor({ timeout: 10000 });
  await page.getByRole('button', { name: 'Reset view', exact: true }).click();
  const add = page.getByRole('button', { name: 'Add teddy', exact: true });
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Add teddy')?.disabled, { timeout: 30000 });
  await add.focus();
  await page.screenshot({ path: `${out}/01-room.png` });
  const snapshot = async () => {
    const value = await page.evaluate(() => window.__evaBedroom?.snapshot());
    assert.ok(value, 'Development snapshot is required; do not report skipped checks as passes.');
    return value;
  };
  const before = await snapshot();
  await add.press('Enter');
  await page.getByRole('status').filter({ hasText: 'A cream teddy is on the bed' }).waitFor();
  const added = await snapshot();
  assert.equal(added.teddySurfaceWrites, 0, 'Default Matrix must not draw solid teddy surfaces');
  assert.ok(added.teddyPoints > 3000 && added.teddyPoints < 60000);
  assert.ok(added.points > before.points + 3000, 'Real renderer draws the teddy point cloud');
  await page.screenshot({ path: `${out}/02-teddy.png` });
  await add.hover();
  const contrast = await add.evaluate(button => {
    const style = getComputedStyle(button);
    const luminance = text => {
      const [r, g, b] = text.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => v / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4);
      return .2126 * r + .7152 * g + .0722 * b;
    };
    const fg = luminance(style.color), bg = luminance(style.backgroundColor);
    return (Math.max(fg, bg) + .05) / (Math.min(fg, bg) + .05);
  });
  assert.ok(contrast >= 3, 'Disabled Add teddy label remains readable on hover');
  await page.getByRole('button', { name: 'Make it blue', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'The teddy is blue' }).waitFor();
  await page.screenshot({ path: `${out}/03-blue.png` });
  await page.getByRole('button', { name: 'Remove teddy', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'The blue teddy is back' }).waitFor();
  const restored = await snapshot();
  assert.deepEqual(restored.camera, before.camera);
  assert.equal(restored.sourceVertices, 622077);
  assert.equal(restored.sourceTriangles, 1144903);
  assert.equal(restored.teddyVisible, true);
  assert.equal(restored.teddyColor, '7caec8');
  await page.getByRole('button', { name: 'Matrix', exact: true }).click();
  await page.screenshot({ path: `${out}/04-matrix.png` });
  const matrix = await snapshot();
  assert.deepEqual(matrix.camera, restored.camera);
  await page.getByRole('button', { name: 'Surfaces', exact: true }).click();
  const surface = await snapshot();
  assert.equal(surface.teddyPoints, 0);
  assert.ok(surface.teddySurfaceWrites > 0);
  assert.deepEqual(surface.teddyAnchor, before.teddyAnchor);
  for (let i = 0; i < 10; i++) {
    await page.getByRole('button', { name: 'Matrix', exact: true }).click();
    assert.equal((await snapshot()).teddySurfaceWrites, 0);
    await page.getByRole('button', { name: 'Surfaces', exact: true }).click();
  }
  assert.equal((await snapshot()).geometries, surface.geometries, 'Repeated representation switches reuse GPU geometry');
  await page.screenshot({ path: `${out}/04-blue-surface.png` });
  const canvas = page.getByRole('application', { name: /Interactive bedroom/ });
  await canvas.focus(); await page.keyboard.press('ArrowLeft');
  const moved = await snapshot();
  assert.notDeepEqual(moved.camera, restored.camera);
  await page.keyboard.press('Home');
  assert.deepEqual((await snapshot()).camera, before.camera);
  await page.keyboard.press('Control+-');
  assert.deepEqual((await snapshot()).camera, before.camera, 'Browser zoom shortcut must not move the scene');
  await page.getByText('Sources & details', { exact: true }).click();
  await page.getByRole('heading', { name: 'A scan, and imagined objects', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.screenshot({ path: `${out}/05-restored.png` });
  const touches = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await touches.newPage();
  await mobile.goto(url);
  await mobile.getByRole('button', { name: 'Reset view', exact: true }).tap();
  await mobile.getByRole('button', { name: 'Add teddy', exact: true }).tap({ timeout: 30000 });
  await mobile.getByRole('button', { name: 'Make it blue', exact: true }).tap();
  const touchCamera = await mobile.evaluate(() => window.__evaBedroom.snapshot().camera);
  const cdp = await touches.newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 150, y: 310 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 200, y: 330 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.notDeepEqual(await mobile.evaluate(() => window.__evaBedroom.snapshot().camera), touchCamera, 'Touch drag changes the view');
  await mobile.getByRole('button', { name: 'Reset view', exact: true }).tap();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 120, y: 310 }, { x: 230, y: 310 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 90, y: 310 }, { x: 260, y: 310 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  const pinched = await mobile.evaluate(() => window.__evaBedroom.snapshot().camera);
  const distance = camera => Math.hypot(...camera.position.map((v, i) => v - camera.target[i]));
  assert.ok(distance(pinched) < distance(touchCamera), 'Pinching outward moves closer');
  await mobile.getByRole('button', { name: 'Reset view', exact: true }).tap();
  await cdp.detach();
  await mobile.screenshot({ path: `${out}/06-touch.png` });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const tinyButtons = await mobile.locator('button:visible').evaluateAll(buttons => buttons.filter(b => b.getBoundingClientRect().height < 44).map(b => b.textContent));
  assert.deepEqual(tinyButtons, []);
  await touches.close();
  assert.deepEqual(errors, []);
  await writeFile(`${out}/checks.json`, JSON.stringify({ url, viewport: [1440, 900], reducedMotion: true, before, added, restored, matrix, surface, errors, checks: ['teddy default Matrix points', 'no solid teddy in Matrix', 'stable GPU geometry across modes', 'keyboard add', 'recolour', 'remove/undo', 'camera continuity', 'source counts', 'mode continuity', 'keyboard navigation', 'details Escape', 'touch presets', 'mobile overflow', '44px buttons'] }, null, 2));
  console.log('PASS: bedroom presets, continuity, keyboard, touch, reduced-motion and captures');
} finally { await context.close(); await browser.close(); }
