// Local browser checks and reproducible evidence. No publication or private inputs.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
const manifest = JSON.parse(readFileSync(new URL('../public/assets/hypersim-full-room-v5/scene.json', import.meta.url)));
import path from 'node:path';
const output = process.argv[2];
const url = process.argv[3] ?? 'http://127.0.0.1:1440/';
if (!output || existsSync(output)) throw new Error('Supply a fresh evidence directory');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const result = { browser: browser.version(), url, viewport: { width: 1440, height: 1000 }, checks: [], errors: [], limitation: 'Headless Edge on Windows; touch emulation, not a physical phone or native Tauri run.' };
const check = name => result.checks.push(name);
const ready = page => page.getByRole('button', { name: 'Reset selected view' }).waitFor();
const snapshot = page => page.evaluate(() => window.__evaRoom.snapshot());
const shot = (page, name) => page.screenshot({ path: path.join(output, name + '.png'), animations: 'disabled' });
try {
  const page = await browser.newPage({ viewport: result.viewport, deviceScaleFactor: 1 });
  page.on('pageerror', e => result.errors.push(e.message));
  const started = Date.now(); await page.goto(url); await ready(page);
  result.initialReadyMs = Date.now() - started;
  result.initial = await snapshot(page);
  assert.equal(result.initial.triangles, manifest.triangles); check('actual mesh loaded and rendered');
  await shot(page, 'desktop-surfaces');
  await page.getByRole('button', { name: 'Points', exact: true }).click();
  const sampled = await snapshot(page);
  assert.equal(sampled.points, sampled.totalPointCount);
  assert.ok(sampled.points > 1000 && sampled.points < manifest.vertices / 10);
  check('simplified points render fewer than one tenth of mesh vertices');
  await shot(page, 'desktop-points');
  await page.getByRole('button', { name: 'Sources & details' }).click();
  const assumedToggle = page.getByRole('checkbox', { name: 'Show assumed adjoining spaces' });
  await assumedToggle.uncheck();
  assert.equal((await snapshot(page)).points, sampled.sourcePointCount);
  assert.deepEqual((await snapshot(page)).position, sampled.position);
  assert.deepEqual((await snapshot(page)).quaternion, sampled.quaternion);
  await assumedToggle.check();
  assert.equal((await snapshot(page)).points, sampled.totalPointCount);
  await assumedToggle.focus(); await page.keyboard.press('Space');
  assert.equal((await snapshot(page)).assumedSpace, false);
  await page.keyboard.press('Space');
  assert.equal((await snapshot(page)).assumedSpace, true);
  await page.getByRole('button', { name: 'Close sources' }).click();
  check('assumed-space toggle removes only its points and preserves camera');
  const originalPose = await snapshot(page);
  await page.getByRole('button', { name: 'Provenance', exact: true }).click();
  assert.equal((await snapshot(page)).mode, 'provenance');
  assert.deepEqual((await snapshot(page)).position, originalPose.position);
  await shot(page, 'desktop-provenance'); check('provenance colors preserve camera and geometry');
  await page.getByRole('button', { name: 'Surfaces', exact: true }).click();
  await page.getByRole('button', { name: 'Sources & details' }).click();
  await assumedToggle.uncheck();
  assert.equal((await snapshot(page)).triangles, manifest.base_candidate_triangles);
  await assumedToggle.check();
  assert.equal((await snapshot(page)).triangles, manifest.triangles);
  await page.getByRole('button', { name: 'Close sources' }).click();
  check('assumed-space toggle restores exact original triangle range');
  const canvas = page.locator('canvas'); await canvas.focus(); await page.keyboard.press('w'); await page.keyboard.press('ArrowRight');
  assert.notDeepEqual((await snapshot(page)).position, result.initial.position);
  assert.notDeepEqual((await snapshot(page)).quaternion, result.initial.quaternion);
  await page.keyboard.press('Home'); assert.deepEqual((await snapshot(page)).position, result.initial.position);
  assert.deepEqual((await snapshot(page)).quaternion, result.initial.quaternion); check('keyboard move/look and exact Home reset');
  await shot(page, 'desktop-keyboard-focus');
  for (const key of ['a','a','s','s','ArrowRight','ArrowRight','d','w','ArrowLeft']) { await page.keyboard.press(key); }
  await shot(page, 'desktop-walk');
  await page.keyboard.press('Home'); check('continuous keyboard navigation and reset after completion');
  await page.mouse.move(680, 400); await page.mouse.down(); await page.mouse.move(740, 430, { steps: 6 }); await page.mouse.up();
  assert.notDeepEqual((await snapshot(page)).quaternion, result.initial.quaternion); check('mouse drag looks around');
  const moved = await snapshot(page);
  await page.getByRole('button', { name: 'Sources & details' }).click();
  assert.equal(await page.getByRole('button', { name: 'Close sources' }).evaluate(e => document.activeElement === e), true);
  assert.deepEqual((await snapshot(page)).position, moved.position);
  assert.deepEqual((await snapshot(page)).quaternion, moved.quaternion);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Sources & details' }).evaluate(e => document.activeElement === e), true);
  check('source open/close preserves camera and restores focus');
  await page.getByRole('button', { name: 'The doorway View 0037' }).click();
  await page.getByRole('button', { name: 'Sources & details' }).click();
  assert.equal(await page.locator('.room-gap-note').count(), 0);
  assert.ok((await page.locator('.room-facts').innerText()).includes((manifest.views.find(v => v.frame === 37).evaluation.hit_coverage * 100).toFixed(2) + '%'));
  assert.match(await page.locator('.room-sources').innerText(), /not held-out accuracy/); check('completion coverage and inference limits are explicit');
  await shot(page, 'desktop-doorway-source');
  await page.getByRole('button', { name: 'Close sources' }).click();
  await shot(page, 'desktop-doorway');
  await page.getByRole('button', { name: 'The cabinet View 0012' }).click();
  await page.getByRole('button', { name: 'Sources & details' }).click(); await shot(page, 'desktop-source');
  await page.getByRole('button', { name: 'Close sources' }).click();
  await page.evaluate(() => { const c = document.querySelector('canvas'); c.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext(); });
  await page.getByRole('alert').waitFor(); await shot(page, 'context-loss');
  await page.getByRole('button', { name: 'Reload room' }).click(); await ready(page); check('context loss exposes error and reload recovers');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  mobile.on('pageerror', e => result.errors.push(e.message));
  await mobile.goto(url); await ready(mobile); await shot(mobile, 'phone-surfaces');
  const idle = await snapshot(mobile); await mobile.waitForTimeout(400);
  assert.deepEqual(await snapshot(mobile), idle); check('reduced motion has no automatic movement');
  const cdp = await mobile.context().newCDPSession(mobile);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 350 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 230, y: 380 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.notDeepEqual((await snapshot(mobile)).quaternion, idle.quaternion);
  // Separate gestures so Chromium can finish dispatching the preceding touch sequence.
  await mobile.waitForTimeout(350);
  await mobile.getByRole('button', { name: 'Move forward', exact: true }).tap();
  await mobile.waitForFunction(position => JSON.stringify(window.__evaRoom.snapshot().position) !== JSON.stringify(position), idle.position);
  assert.notDeepEqual((await snapshot(mobile)).position, idle.position); check('emulated touch drag and movement button');
  await mobile.getByRole('button', { name: 'Reset selected view' }).tap();
  await mobile.getByRole('button', { name: 'Sources & details' }).tap();
  assert.equal(await mobile.locator('.room-stage').evaluate(e => e.inert), true);
  await mobile.keyboard.press('Shift+Tab');
  assert.equal(await mobile.getByRole('link', { name: 'Asset provenance' }).evaluate(e => document.activeElement === e), true);
  await mobile.keyboard.press('Tab');
  assert.equal(await mobile.getByRole('button', { name: 'Close sources' }).evaluate(e => document.activeElement === e), true);
  await shot(mobile, 'phone-source'); await mobile.keyboard.press('Escape');
  assert.equal(await mobile.locator('#room-sources').count(), 0); check('phone source dialog focus trap, Escape and inert background');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true); check('phone has no horizontal overflow');
  await mobile.getByRole('button', { name: 'Sources & details' }).tap();
  const phoneToggle = mobile.getByRole('checkbox', { name: 'Show assumed adjoining spaces' });
  const phonePose = await snapshot(mobile);
  await phoneToggle.tap();
  assert.equal((await snapshot(mobile)).assumedSpace, false);
  assert.deepEqual((await snapshot(mobile)).position, phonePose.position);
  await phoneToggle.tap();
  assert.equal((await snapshot(mobile)).assumedSpace, true);
  await mobile.keyboard.press('Escape');
  check('assumed-space checkbox supports touch without moving the camera');
  const cancelled = await browser.newPage({ viewport: result.viewport });
  let release; const gate = new Promise(resolve => { release = resolve; });
  await cancelled.route('**/room.ply', async route => { await gate; try { await route.continue(); } catch {} });
  await cancelled.goto(url); await cancelled.getByRole('button', { name: 'Cancel loading' }).click();
  release(); await cancelled.waitForTimeout(300);
  assert.equal(await cancelled.getByRole('heading', { name: 'Loading paused' }).isVisible(), true);
  await shot(cancelled, 'cancelled'); await cancelled.unroute('**/room.ply');
  await cancelled.getByRole('button', { name: 'Reload room' }).click(); await ready(cancelled); check('cancelled loading cannot resurrect; explicit reload succeeds');
  const failed = await browser.newPage({ viewport: result.viewport });
  await failed.route('**/room.ply', route => route.fulfill({ status: 200, body: 'truncated' }));
  await failed.goto(url); await failed.getByRole('alert').waitFor();
  assert.match(await failed.getByRole('alert').innerText(), /incomplete/);
  await shot(failed, 'failed-download'); await failed.unroute('**/room.ply');
  await failed.getByRole('button', { name: 'Reload room' }).click(); await ready(failed); check('truncated mesh rejected and retry succeeds');
  const interrupted = await browser.newPage();
  let resume; const pause = new Promise(resolve => { resume = resolve; });
  await interrupted.route('**/room.ply', async route => { await pause; try { await route.continue(); } catch {} });
  await interrupted.goto(url);
  await interrupted.waitForFunction(() => window.__evaRoom);
  await interrupted.evaluate(() => document.querySelector('canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
  await interrupted.getByRole('alert').waitFor(); resume(); await interrupted.waitForTimeout(400);
  assert.equal(await interrupted.getByRole('alert').isVisible(), true);
  await interrupted.unroute('**/room.ply'); await interrupted.getByRole('button', { name: 'Reload room' }).click(); await ready(interrupted);
  check('context loss during loading stays failed until explicit reload');
  assert.deepEqual(result.errors, []); result.status = 'passed';
} catch (error) { result.status = 'failed'; result.failure = String(error.stack ?? error); throw error; }
finally { await writeFile(path.join(output, 'checks.json'), JSON.stringify(result, null, 2)); await browser.close(); }
